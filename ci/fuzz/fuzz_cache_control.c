/*
 * libFuzzer harness for the origin Cache-Control / Surrogate-Control parser:
 * cc_token, cc_has, cc_parse_delta, cc_delta and cc_delta_all.
 *
 * Why this target: the response header values are attacker-controlled bytes
 * from the origin. The tokenizer walks them with pointer arithmetic around a
 * quoted-string / quoted-pair state machine (unterminated quotes, a trailing
 * backslash, '=' with no value), and the delta parser does saturating decimal
 * accumulation. Bug classes: OOB read at/over `last` (every value is an
 * exact-sized, NON-NUL-terminated heap buffer so ASan sees it) and integer
 * overflow.
 *
 * Input layout:
 *   byte 0       directive selector (index into kNames) | bit 7: header name
 *                (0 = Cache-Control, 1 = Surrogate-Control)
 *   bytes 1..    header field-line values separated by 0xFF. The first byte
 *                of each field-line is a tag: low 2 bits pick the stored key
 *                (Cache-Control, Surrogate-Control, "cache-CONTROL", X-Other),
 *                bit 2 clears the table hash (a deleted element). The rest is
 *                the value. Field-lines are spread over list parts of 3
 *                elements so the part->next walk is exercised.
 *
 * Oracle (independent reference model written below, not a copy of the
 * production code; contract read from the source comments of
 * cc_parse_delta / cc_delta / cc_delta_all):
 *   - cc_parse_delta: one optional surrounding quote pair, then 1+ ASCII
 *     digits and nothing else -> the decimal value, saturating at
 *     NGX_MAX_TIME_T_VALUE; anything else (empty, sign, space, escape,
 *     digit-prefixed junk) -> -1, the only negative result.
 *   - cc_token/cc_has/cc_delta: the first full-token, case-insensitive match
 *     of the directive; cc_delta is -1 when absent/bare/empty-valued.
 *   - cc_delta_all: the first field-line (hash != 0, key equal ignoring case)
 *     whose cc_delta is >= 0, else -1.
 *
 * Bodies are sliced by extract_cache_control.sh into
 * generated_cache_control.inc. Build: ci/fuzz/build.sh.
 */

#include "ngx_shim_cc.h"

/* Generated by ci/fuzz/extract_cache_control.sh. */
#include "generated_cache_control.inc"

#define TRAP()  __builtin_trap()

static const char *const kNames[] = {
    "max-age", "s-maxage", "stale-while-revalidate", "stale-if-error",
    "no-cache", "no-store", "private", "public", "must-revalidate", "a"
};
#define NNAMES  (sizeof(kNames) / sizeof(kNames[0]))

static int
lc(int c)
{
    return (c >= 'A' && c <= 'Z') ? c + 32 : c;
}

/* Reference: first token matching name in [p,last). Returns 1 when found and
 * fills value start/len and eq; 0 otherwise. Independent structure: collect
 * token boundaries first, then test them. */
static int
ref_find(const u_char *p, const u_char *last, const char *name,
    const u_char **val, size_t *vlen, int *has_eq, size_t *resume)
{
    size_t   nlen = strlen(name);
    size_t   pos = 0, n = (size_t) (last - p);

    while (pos < n) {
        size_t  a, b, i, q = 0, esc = 0;

        while (pos < n && (p[pos] == ' ' || p[pos] == '\t' || p[pos] == ',')) {
            pos++;
        }
        a = pos;
        for (b = pos; b < n; b++) {
            if (q) {
                if (esc) {
                    esc = 0;
                } else if (p[b] == '\\') {
                    esc = 1;
                } else if (p[b] == '"') {
                    q = 0;
                }
            } else if (p[b] == '"') {
                q = 1;
            } else if (p[b] == ',') {
                break;
            }
        }
        pos = b + 1;
        while (b > a && (p[b - 1] == ' ' || p[b - 1] == '\t')) {
            b--;
        }
        for (i = a; i < b && p[i] != '='; i++) {
            /* find '=' */
        }
        if (i - a == nlen) {
            size_t k;
            for (k = 0; k < nlen; k++) {
                if (lc(p[a + k]) != lc((u_char) name[k])) {
                    break;
                }
            }
            if (k == nlen) {
                *has_eq = (i < b);
                *val = (i < b) ? p + i + 1 : p + a;
                *vlen = (i < b) ? b - (i + 1) : 0;
                if (resume != NULL) {
                    *resume = pos < n ? pos : n;    /* start of the next token */
                }
                return 1;
            }
        }
    }
    return 0;
}

static long long
ref_delta_value(const u_char *p, size_t len)
{
    unsigned __int128  v = 0;
    size_t             i;

    if (len >= 2 && p[0] == '"' && p[len - 1] == '"') {
        p++;
        len -= 2;
    }
    if (len == 0) {
        return -1;
    }
    for (i = 0; i < len; i++) {
        if (p[i] < '0' || p[i] > '9') {
            return -1;
        }
        v = v * 10 + (unsigned) (p[i] - '0');
        if (v > (unsigned __int128) NGX_MAX_TIME_T_VALUE) {
            v = (unsigned __int128) NGX_MAX_TIME_T_VALUE;
        }
    }
    return (long long) v;
}

static long long
ref_delta(const u_char *p, const u_char *last, const char *name)
{
    const u_char  *val;
    size_t         vlen;
    int            eq;

    if (!ref_find(p, last, name, &val, &vlen, &eq, NULL) || vlen == 0) {
        return -1;
    }
    return ref_delta_value(val, vlen);
}

/* Exact-sized heap copy; len 0 still gets a real 1-byte allocation. */
static u_char *
dup_exact(const uint8_t *s, size_t n)
{
    u_char *b = (u_char *) malloc(n ? n : 1);

    if (b == NULL) {
        abort();
    }
    if (n) {
        memcpy(b, s, n);
    }
    return b;
}

#define PART_ELTS  3
#define MAX_LINES  1100

typedef struct {
    ngx_list_part_t  part;
    ngx_table_elt_t  elts[PART_ELTS];
} fuzz_part_t;

int
LLVMFuzzerTestOneInput(const uint8_t *data, size_t size)
{
    static const char *const kKeys[4] = {
        "Cache-Control", "Surrogate-Control", "cache-CONTROL", "X-Other"
    };
    const char     *hname, *name;
    size_t          hnlen, nlen, pos, nlines = 0, nparts = 0, i;
    fuzz_part_t    *parts[MAX_LINES / PART_ELTS + 2];
    u_char         *bufs[2 * MAX_LINES];
    size_t          nbufs = 0;
    ngx_list_t      list;
    ngx_table_elt_t lines[MAX_LINES];
    time_t          got;
    long long       want;

    if (size < 1) {
        return 0;
    }
    name = kNames[(data[0] & 0x7f) % NNAMES];
    nlen = strlen(name);
    hname = (data[0] & 0x80) ? "Surrogate-Control" : "Cache-Control";
    hnlen = strlen(hname);
    data++;
    size--;

    /* Split into field-lines. */
    pos = 0;
    while (nlines < MAX_LINES) {
        size_t        end = pos;
        const uint8_t *chunk = data + pos;
        uint8_t        tag = 0;
        size_t         clen, vstart = 0;
        const char    *key;
        ngx_table_elt_t *e = &lines[nlines];

        while (end < size && data[end] != 0xFF) {
            end++;
        }
        clen = end - pos;
        if (clen > 0) {
            tag = chunk[0];
            vstart = 1;
        }
        key = kKeys[tag & 3];
        e->hash = (tag & 4) ? 0 : 1;
        e->key.len = strlen(key);
        e->key.data = dup_exact((const uint8_t *) key, e->key.len);
        bufs[nbufs++] = e->key.data;
        e->value.len = clen - vstart;
        e->value.data = dup_exact(chunk + vstart, e->value.len);
        bufs[nbufs++] = e->value.data;
        nlines++;
        if (end >= size) {
            break;
        }
        pos = end + 1;
    }

    /* Build the chained list: every part is heap-allocated; the head part
     * header is copied into list.part (as ngx_list_init does in place). */
    memset(&list, 0, sizeof(list));
    {
        ngx_list_part_t *prev = NULL;

        for (i = 0; i < nlines; i += PART_ELTS) {
            fuzz_part_t *fp = (fuzz_part_t *) calloc(1, sizeof(*fp));
            size_t       k, m = nlines - i < PART_ELTS ? nlines - i : PART_ELTS;

            if (fp == NULL) {
                abort();
            }
            for (k = 0; k < m; k++) {
                fp->elts[k] = lines[i + k];
            }
            fp->part.elts = fp->elts;
            fp->part.nelts = m;
            parts[nparts++] = fp;
            if (prev == NULL) {
                list.part = fp->part;
                prev = &list.part;
            } else {
                prev->next = &fp->part;
                prev = &fp->part;
            }
        }
        list.last = prev;
    }

    /* Per-value checks over every line. */
    for (i = 0; i < nlines; i++) {
        u_char       *v = lines[i].value.data, *e = v + lines[i].value.len;
        u_char       *cur = v, *q;
        size_t        vlen, steps = 0;
        ngx_int_t     valued = -1;
        const u_char *rv;
        size_t        rvlen;
        int           req, rfound;

        rfound = ref_find(v, e, name, &rv, &rvlen, &req, NULL);
        if ((ngx_http_cache_turbo_cc_has(v, e, name, nlen) != 0) != rfound) {
            TRAP();
        }

        q = ngx_http_cache_turbo_cc_token(&cur, e, name, nlen, &vlen, &valued);
        if ((q != NULL) != rfound) {
            TRAP();
        }
        if (q != NULL) {
            if (q < v || q > e || vlen > (size_t) (e - q)
                || q != rv || vlen != rvlen || valued != req)
            {
                TRAP();
            }
        }
        if (cur < v || cur > e) {
            TRAP();
        }

        /* Repeated-scan loop as in the request path (max-age/min-fresh): every
         * result must be the next reference match, in order, with the same
         * value and valued flag; when the production tokenizer returns NULL the
         * reference must be exhausted too. A tokenizer that stopped after the
         * first of several matching directives fails here. */
        cur = v;
        {
            size_t         rpos = 0, rres;
            const u_char  *nrv;
            size_t         nrvlen;
            int            nreq, nfound;

            for ( ;; ) {
                valued = -1;
                q = ngx_http_cache_turbo_cc_token(&cur, e, name, nlen, &vlen,
                                                  &valued);
                nfound = ref_find(v + rpos, e, name, &nrv, &nrvlen, &nreq,
                                  &rres);
                if ((q != NULL) != nfound) {
                    TRAP();
                }
                if (q == NULL) {
                    break;
                }
                if (cur < v || cur > e || q < v || q > e
                    || ++steps > lines[i].value.len + 1
                    || q != nrv || vlen != nrvlen || valued != nreq
                    || cur != v + rpos + rres)
                {
                    TRAP();
                }
                rpos += rres;
            }
        }

        want = ref_delta(v, e, name);
        got = ngx_http_cache_turbo_cc_delta(v, e, name, nlen);
        if (got < -1 || (long long) got != want) {
            TRAP();
        }

        /* parse_delta directly on the raw value: contract is -1 or >= 0. */
        got = ngx_http_cache_turbo_cc_parse_delta(v, lines[i].value.len);
        if (got < -1 || (long long) got != ref_delta_value(v,
                                                           lines[i].value.len))
        {
            TRAP();
        }
    }

    /* delta_all reference: first matching, hashed, key-equal line with
     * delta >= 0. */
    want = -1;
    for (i = 0; i < nlines; i++) {
        long long  t;

        if (lines[i].hash == 0 || lines[i].key.len != hnlen
            || strncasecmp((const char *) lines[i].key.data, hname, hnlen) != 0)
        {
            continue;
        }
        t = ref_delta(lines[i].value.data,
                      lines[i].value.data + lines[i].value.len, name);
        if (t >= 0) {
            want = t;
            break;
        }
    }
    got = ngx_http_cache_turbo_cc_delta_all(&list, hname, hnlen, name, nlen);
    if (got < -1 || (long long) got != want) {
        TRAP();
    }

    for (i = 0; i < nbufs; i++) {
        free(bufs[i]);
    }
    for (i = 0; i < nparts; i++) {
        free(parts[i]);
    }
    return 0;
}
