/*
 * libFuzzer harness for the origin Vary classifier: the comma/whitespace
 * tokeniser (classify_vary_next_token), the per-axis verdict
 * (classify_vary_classify_token) and the cache_turbo_vary_ignore lookup
 * (vary_ignore_match).
 *
 * Why this target: the response Vary value is attacker-controlled bytes from
 * the origin, and the classifier is the security gate that decides whether a
 * response may be stored at all. Bug classes: an OOB read at/over the end of
 * an exact-sized, NON-NUL-terminated value (every value, token and ignore
 * entry here is its own heap buffer so ASan sees it), a tokeniser that fails
 * to advance, and a fail-OPEN verdict (a Vary axis the whitelist has no bit
 * for must never leave the response cacheable).
 *
 * Input layout:
 *   byte 0   bit 0     response_encoded (Accept-Encoding bit on/off)
 *            bits 1-2  clcf mode: 0 = clcf NULL, 1 = vary_ignore
 *                      NGX_CONF_UNSET_PTR, 2 = array built from byte 1,
 *                      3 = empty array
 *   byte 1   mask over kIgnore[]: which names the harness-built
 *            cache_turbo_vary_ignore list holds (mode 2 only)
 *   bytes 2..  Vary field-line values separated by 0xFF, each its own
 *            exact-sized heap buffer; verdicts accumulate across lines
 *            exactly as the shipped caller does.
 *
 * The driving loop below is the shipped caller's inner loop
 * (ngx_http_cache_turbo_classify_vary): next_token, then ignore_match, then
 * classify_token, finishing with "a refused axis wins: bits = 0 on nocache".
 * The preset_satisfied step (needs a request) is not driven.
 *
 * Oracle (independent reference model; contract read from the source
 * comments of classify_token / vary_ignore_match, not a copy of the code):
 *   Known-token set, derived from the shipped classify_token arms:
 *     veto, named:     "*", Cookie, Authorization
 *     whitelist:       Accept-Encoding (bit only when response_encoded),
 *                      User-Agent, Accept-Language, Origin
 *     anything else:   unknown -> nocache AND unsafe_axis.
 *   Matching is exact-length and ASCII case-insensitive.
 *   1. Exact model: the reference loop computes (bits, nocache, unsafe_axis)
 *      with its own tokeniser and must equal the shipped result.
 *   2. Fail-closed property: if any non-ignored token is outside the
 *      whitelist (an unknown token, or one of the named vetoes) the final
 *      verdict MUST be nocache = 1 with bits = 0, and an unknown token must
 *      also set unsafe_axis. Checked separately from (1) so a drift in the
 *      model cannot mask a fail-open classifier.
 *   3. Tokeniser: a returned token lies inside [value, end), is non-empty and
 *      free of separators, the cursor always advances, and a 0 return means
 *      the value is exhausted.
 *
 * Bodies are sliced by extract_vary.sh into generated_vary.inc.
 * Build: ci/fuzz/build.sh.
 */

#include "ngx_shim_vary.h"

/* Generated by ci/fuzz/extract_vary.sh. */
#include "generated_vary.inc"

#define TRAP()  __builtin_trap()

#define MAX_LINES  64

static const char *const kIgnore[] = {
    "Accept", "X-Custom", "cookie", "*", "User-Agent", "Origin"
};
#define NIGNORE  (sizeof(kIgnore) / sizeof(kIgnore[0]))

static u_char *
dup_exact(const uint8_t *p, size_t n)
{
    u_char  *d = malloc(n ? n : 1);

    if (d == NULL) {
        abort();
    }
    if (n) {
        memcpy(d, p, n);
    }
    return d;
}

static int
lc(int c)
{
    return (c >= 'A' && c <= 'Z') ? c + 32 : c;
}

/* Exact-length, ASCII case-insensitive equality (reference, no libc). */
static int
ref_eq(const u_char *p, size_t n, const char *name)
{
    size_t  i;

    if (strlen(name) != n) {
        return 0;
    }
    for (i = 0; i < n; i++) {
        if (lc(p[i]) != lc((u_char) name[i])) {
            return 0;
        }
    }
    return 1;
}

static int
ref_sep(int c)
{
    return c == ' ' || c == '\t' || c == ',';
}

typedef struct {
    ngx_int_t    bits;
    ngx_uint_t   nocache;
    ngx_uint_t   unsafe_axis;
    int          refused;   /* a non-ignored token outside the whitelist */
    int          unknown;   /* a non-ignored token no arm names */
} verdict_t;

static void
ref_token(verdict_t *v, const u_char *t, size_t n, int resp_enc)
{
    if (ref_eq(t, n, "*") || ref_eq(t, n, "Cookie")
        || ref_eq(t, n, "Authorization"))
    {
        v->nocache = 1;
        v->refused = 1;
    } else if (ref_eq(t, n, "Accept-Encoding")) {
        if (resp_enc) {
            v->bits |= NGX_HTTP_CACHE_TURBO_VARY_ENCODING;
        }
    } else if (ref_eq(t, n, "User-Agent")) {
        v->bits |= NGX_HTTP_CACHE_TURBO_VARY_DEVICE;
    } else if (ref_eq(t, n, "Accept-Language")) {
        v->bits |= NGX_HTTP_CACHE_TURBO_VARY_LANG;
    } else if (ref_eq(t, n, "Origin")) {
        v->bits |= NGX_HTTP_CACHE_TURBO_VARY_ORIGIN;
    } else {
        v->nocache = 1;
        v->unsafe_axis = 1;
        v->refused = 1;
        v->unknown = 1;
    }
}

/* Reference over one value: independent tokeniser (index scan, not the
 * pointer-advance shape of the shipped one). */
static void
ref_value(verdict_t *v, const u_char *p, size_t n, int resp_enc,
    int ign_mode, unsigned ign_mask)
{
    size_t  pos = 0, a, i;

    while (pos < n) {
        int  ignored = 0;

        if (ref_sep(p[pos])) {
            pos++;
            continue;
        }
        a = pos;
        while (pos < n && !ref_sep(p[pos])) {
            pos++;
        }
        if (ign_mode == 2) {
            for (i = 0; i < NIGNORE; i++) {
                if ((ign_mask >> i & 1) && ref_eq(p + a, pos - a, kIgnore[i])) {
                    ignored = 1;
                }
            }
        }
        if (!ignored) {
            ref_token(v, p + a, pos - a, resp_enc);
        }
    }
}

int
LLVMFuzzerTestOneInput(const uint8_t *data, size_t size)
{
    int                               resp_enc, mode;
    unsigned                          mask;
    size_t                            pos, nlines = 0, nbufs = 0, i;
    u_char                           *bufs[MAX_LINES + NIGNORE];
    u_char                           *vals[MAX_LINES];
    size_t                            lens[MAX_LINES];
    ngx_str_t                         ign[NIGNORE];
    ngx_array_t                       arr;
    ngx_http_cache_turbo_loc_conf_t   clcf_s, *clcf = NULL;
    ngx_int_t                         bits = 0;
    ngx_uint_t                        nocache = 0, unsafe_axis = 0;
    verdict_t                         ref;

    if (size < 2) {
        return 0;
    }
    resp_enc = data[0] & 1;
    mode = (data[0] >> 1) & 3;
    mask = data[1] & ((1u << NIGNORE) - 1);
    data += 2;
    size -= 2;

    /* Harness-built cache_turbo_vary_ignore list. */
    memset(&arr, 0, sizeof(arr));
    clcf_s.vary_ignore = NULL;
    if (mode == 0) {
        clcf = NULL;
    } else {
        clcf = &clcf_s;
        if (mode == 1) {
            clcf_s.vary_ignore = NGX_CONF_UNSET_PTR;
        } else {
            size_t  n = 0;

            if (mode == 2) {
                for (i = 0; i < NIGNORE; i++) {
                    if (mask >> i & 1) {
                        ign[n].len = strlen(kIgnore[i]);
                        ign[n].data = dup_exact((const uint8_t *) kIgnore[i],
                                                ign[n].len);
                        bufs[nbufs++] = ign[n].data;
                        n++;
                    }
                }
            }
            arr.elts = n ? (void *) ign : NULL;
            arr.nelts = n;
            clcf_s.vary_ignore = &arr;
        }
    }

    /* Split into field-line values. */
    pos = 0;
    while (nlines < MAX_LINES) {
        size_t  end = pos;

        while (end < size && data[end] != 0xFF) {
            end++;
        }
        lens[nlines] = end - pos;
        vals[nlines] = dup_exact(data + pos, lens[nlines]);
        bufs[nbufs++] = vals[nlines];
        nlines++;
        if (end >= size) {
            break;
        }
        pos = end + 1;
    }

    /* The shipped caller's per-value loop. */
    for (i = 0; i < nlines; i++) {
        u_char  *s = vals[i], *e = s + lens[i], *tok = NULL;
        size_t   tl = 0;

        while (s < e) {
            u_char  *before = s;

            if (!ngx_http_cache_turbo_classify_vary_next_token(&s, e, &tok,
                                                                 &tl))
            {
                if (s != e) {
                    TRAP();     /* 0 return with data left */
                }
                continue;
            }
            if (s <= before || s > e || tl == 0 || tok < vals[i]
                || tok + tl > e || tok + tl > s)
            {
                TRAP();         /* token outside value / no progress */
            }
            for (size_t k = 0; k < tl; k++) {
                if (ref_sep(tok[k])) {
                    TRAP();     /* separator inside token */
                }
            }
            if (ngx_http_cache_turbo_vary_ignore_match(clcf, tok, tl)) {
                continue;
            }
            ngx_http_cache_turbo_classify_vary_classify_token(tok, tl,
                                                                &bits,
                                                                &nocache,
                                                                &unsafe_axis,
                                                                resp_enc);
        }
    }
    if (nocache) {
        bits = 0;
    }

    /* Oracle 1: exact reference model. */
    memset(&ref, 0, sizeof(ref));
    for (i = 0; i < nlines; i++) {
        ref_value(&ref, vals[i], lens[i], resp_enc,
                  (clcf != NULL && mode >= 2) ? 2 : 0,
                  mode == 2 ? mask : 0);
    }
    if (ref.nocache) {
        ref.bits = 0;
    }
    if (bits != ref.bits || nocache != ref.nocache
        || unsafe_axis != ref.unsafe_axis)
    {
        TRAP();
    }

    /* Oracle 2: fail-closed property, independent of the model's arms. */
    if (ref.refused && (!nocache || bits != 0)) {
        TRAP();
    }
    if (ref.unknown && !unsafe_axis) {
        TRAP();
    }

    for (i = 0; i < nbufs; i++) {
        free(bufs[i]);
    }
    return 0;
}
