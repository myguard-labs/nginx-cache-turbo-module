/*
 * libFuzzer harness for the cache-turbo Cookie index, Cookie Aho-Corasick scan
 * and query-string argument parser:
 *   ngx_http_cache_turbo_cookie_index_parse_one()  (+ cookie_index_add)
 *   ngx_http_cache_turbo_cookie_ac_scan_one()
 *   ngx_http_cache_turbo_argparse_tail_count()
 *   ngx_http_cache_turbo_argparse_build()          (+ hexval, qs_first_mangled)
 *
 * Why this target: these four are the attacker-reachable byte walkers behind
 * the key-cookie index, the auto-classify Cookie matcher and the preset query
 * matcher. They scan client Cookie values (";" without a space, empty names,
 * "=" inside values, quoted values, duplicates, thousands of crumbs) and query
 * strings ("&&", bare "=", truncated %-escapes, "+", tens of thousands of
 * args) with pointer arithmetic against exact lengths, and argparse_build
 * allocates its span array from a size computed by a SEPARATE counting walk
 * (argparse_tail_count). Bug classes: an OOB read at/over the end of an
 * exact-sized, NON-NUL-terminated buffer (every value is its own heap block so
 * ASan sees it), a write past an allocation if the counting walk and the
 * recording walk ever disagree, and a Cookie pair/arg mis-split that changes
 * which cookie or argument the cache key and bypass rules see.
 *
 * Function ownership (no overlap with fuzz_auto_classify): the sliced block
 * here is the part of match.c that fuzz_auto_classify's build compiles OUT
 * (cookie_index_*, cookie_ac_scan_one sit under !FUZZ_SHIM_AUTO) plus the
 * argparse pair, which fuzz_auto_classify only reaches as an unasserted
 * feeder of auto_skip. cookie_pred_one_next_pair / _split are compiled and
 * driven by fuzz_auto_classify (cookie_pred over the phpBB/Shopware/Invision
 * predicate rows) and are therefore NOT sliced here. See ci/fuzz/README.md.
 *
 * Input layout:
 *   byte 0   bit 0  pool failure: every ngx_palloc returns NULL
 *            bit 1  the Aho-Corasick automaton holds the empty needle
 *            bit 2  ac->nodes NULL / nnodes 0
 *            bit 3  ac data pointer NULL with a non-zero length
 *   byte 1   mask over kNeedles[]: which needles the harness-built automaton holds
 *   byte 2   offset selector for argparse_tail_count (tail offset = sel % (n+1))
 *   bytes 3..  sections separated by 0xFF: section 0 is the query string, the
 *            sections after it (at most MAX_HDRS) are Cookie header values.
 *            Each is an exact-sized heap buffer, no trailing NUL.
 *
 * Oracle (independent reference models, written from the source comments, with
 * their own index-based tokenisers rather than the pointer-advance shape of the
 * shipped code):
 *   argparse: nspans equals the reference count of non-empty "&"/";" pairs;
 *     every span's name/value offsets equal the reference; the name_first[]
 *     set equals the reference (decode a valid %HH, then literal "+" / "." /
 *     " " -> "_"); BOUND ORACLE: tail_count(args) equals the reference count,
 *     tail_count of any suffix equals the suffix reference, nspans never
 *     exceeds capacity, and an overflowed array's allocation is exactly
 *     capacity * sizeof(span) with nspans == capacity (the computed size).
 *     With a failing pool the result must be NGX_ERROR iff more than
 *     NGX_HTTP_CACHE_TURBO_ARGS_MAX pairs exist, NGX_OK otherwise.
 *   cookie index: pair count, every name/value pointer+length, the bare flag
 *     and first-occurrence-wins duplicate handling equal the reference; an
 *     expanded array's allocation is exactly cap * sizeof(pair). With a
 *     failing pool the result must be NGX_ERROR iff more than 16 distinct
 *     names exist.
 *   cookie_ac_scan_one: equals "any held needle occurs before the first NUL"
 *     (or 1 for a non-empty value when the empty needle is held), and 0 for
 *     NULL data, zero length and an empty automaton.
 *
 * Bodies are sliced by extract_cookie_args.sh into generated_cookie_args.inc.
 * Build: ci/fuzz/build.sh.
 */

#include <stdio.h>

#include "ngx_shim_cookie_args.h"

/* Generated by ci/fuzz/extract_cookie_args.sh. */
#include "generated_cookie_args.inc"

#define FAIL(msg)                                                            \
    do {                                                                     \
        fprintf(stderr, "fuzz_cookie_args: %s\n", msg);                      \
        __builtin_trap();                                                    \
    } while (0)

#define MAX_HDRS      8
#define INLINE_PAIRS  16
#define NO_VALUE      ((size_t) -1)

static const char *const kNeedles[] = {
    "wordpress_logged_in_", "wp-settings-", "PHPSESSID", "_u", "sid", "a;b"
};
#define NNEEDLES  (sizeof(kNeedles) / sizeof(kNeedles[0]))

static u_char *
dup_exact(const uint8_t *p, size_t n)
{
    u_char  *d = malloc(n ? n : 1);

    if (d == NULL) {
        abort();
    }
    if (n) {
        memcpy(d, p, n);
    }
    return d;
}

static int
is_ows(int c)
{
    return c == ' ' || c == '\t';
}

/* ---- query string reference ------------------------------------------- */

typedef struct {
    size_t  a;      /* pair start */
    size_t  ne;     /* name end (the '=' or the pair end) */
    size_t  vs;     /* value start, NO_VALUE when valueless */
    size_t  ve;     /* value end */
} ref_span_t;

static int
ref_asep(int c)
{
    return c == '&' || c == ';';
}

/* Returns the span count; fills out[] (capacity n + 1) when out != NULL. */
static size_t
ref_args(const u_char *p, size_t n, ref_span_t *out)
{
    size_t  pos = 0, a, e, q, cnt = 0;

    while (pos < n) {
        a = pos;
        while (pos < n && !ref_asep(p[pos])) {
            pos++;
        }
        e = pos;
        pos++;                          /* the separator, or one past the end */
        if (e == a) {
            continue;
        }
        if (out != NULL) {
            out[cnt].a = a;
            out[cnt].ne = e;
            out[cnt].vs = NO_VALUE;
            out[cnt].ve = e;
            for (q = a; q < e; q++) {
                if (p[q] == '=') {
                    out[cnt].ne = q;
                    out[cnt].vs = q + 1;
                    break;
                }
            }
        }
        cnt++;
    }
    return cnt;
}

static int
ref_hex(int c)
{
    if (c >= '0' && c <= '9') {
        return c - '0';
    }
    if (c >= 'a' && c <= 'f') {
        return c - 'a' + 10;
    }
    if (c >= 'A' && c <= 'F') {
        return c - 'A' + 10;
    }
    return -1;
}

/* Mangled first byte of the name [a, ne) (precondition a < ne). */
static int
ref_first(const u_char *p, size_t a, size_t ne)
{
    int  c = p[a], decoded = 0;

    if (c == '%' && ne - a >= 3 && ref_hex(p[a + 1]) >= 0
        && ref_hex(p[a + 2]) >= 0)
    {
        c = (ref_hex(p[a + 1]) << 4) | ref_hex(p[a + 2]);
        decoded = 1;
    }
    if (c == '+' && !decoded) {
        return '_';
    }
    if (c == '.' || c == ' ') {
        return '_';
    }
    return c;
}

static void
check_args(const uint8_t *src, size_t n, int pool_fail, unsigned sel)
{
    ngx_http_request_t               r;
    ngx_pool_t                       pool;
    ngx_http_cache_turbo_argparse_t  ap;
    u_char                          *buf;
    ref_span_t                      *ref;
    unsigned char                    first[256];
    size_t                           cnt, i, k, alloc_bytes;
    ngx_int_t                        rc;

    buf = dup_exact(src, n);
    ref = malloc((n + 1) * sizeof(*ref));
    if (ref == NULL) {
        abort();
    }
    cnt = ref_args(buf, n, ref);

    memset(&r, 0, sizeof(r));
    memset(&pool, 0, sizeof(pool));
    pool.fail = pool_fail;
    r.args.data = buf;
    r.args.len = n;
    r.pool = &pool;

    /* Bound oracle, counting walk: the whole string and an arbitrary suffix. */
    if (ngx_http_cache_turbo_argparse_tail_count(buf, buf + n) != cnt) {
        FAIL("argparse_tail_count disagrees with the reference count");
    }
    k = sel % (n + 1);
    if (n && ngx_http_cache_turbo_argparse_tail_count(buf + k, buf + n)
             != ref_args(buf + k, n - k, NULL))
    {
        FAIL("argparse_tail_count of a suffix disagrees with the reference");
    }

    rc = ngx_http_cache_turbo_argparse_build(&r, &ap);

    if (pool_fail && cnt > NGX_HTTP_CACHE_TURBO_ARGS_MAX) {
        if (rc != NGX_ERROR) {
            FAIL("argparse_build did not fail closed on allocation failure");
        }
        goto done;
    }
    if (rc != NGX_OK) {
        FAIL("argparse_build failed with an allocation available");
    }

    /* Bound oracle, recording walk: never more spans than the computed size. */
    if (ap.nspans != cnt) {
        FAIL("argparse_build span count differs from the reference");
    }
    if (ap.nspans > ap.capacity) {
        FAIL("argparse_build recorded more spans than its capacity");
    }
    if (cnt <= NGX_HTTP_CACHE_TURBO_ARGS_MAX) {
        if (ap.spans != ap.inline_spans || pool.nallocs != 0) {
            FAIL("argparse_build allocated for an inline-sized query");
        }
    } else {
        if (ap.spans == ap.inline_spans || pool.nallocs != 1) {
            FAIL("argparse_build did not expand exactly once");
        }
        alloc_bytes = pool.sizes[0];
        if (alloc_bytes != ap.capacity * sizeof(ngx_http_cache_turbo_argspan_t)
            || ap.nspans != ap.capacity
            || ap.nspans * sizeof(ngx_http_cache_turbo_argspan_t)
               > alloc_bytes)
        {
            FAIL("argparse_build output exceeds the computed size");
        }
    }

    for (i = 0; i < cnt; i++) {
        const ngx_http_cache_turbo_argspan_t  *s = &ap.spans[i];

        if (s->name_start != buf + ref[i].a
            || s->name_end != buf + ref[i].ne)
        {
            FAIL("argparse_build name span differs from the reference");
        }
        if (ref[i].vs == NO_VALUE) {
            if (s->value_start != NULL || s->value_end != NULL) {
                FAIL("argparse_build valueless span carries a value");
            }
        } else if (s->value_start != buf + ref[i].vs
                   || s->value_end != buf + ref[i].ve)
        {
            FAIL("argparse_build value span differs from the reference");
        }
    }

    memset(first, 0, sizeof(first));
    for (i = 0; i < cnt; i++) {
        if (ref[i].a < ref[i].ne) {
            first[ref_first(buf, ref[i].a, ref[i].ne)] = 1;
        }
    }
    if (memcmp(first, ap.name_first, sizeof(first)) != 0) {
        FAIL("argparse_build name_first set differs from the reference");
    }

done:
    ngx_fuzz_pool_reset(&pool);
    free(ref);
    free(buf);
}

/* ---- Cookie index reference ------------------------------------------- */

typedef struct {
    size_t  hdr;
    size_t  noff, nlen;
    size_t  voff, vlen;
    int     bare;
} ref_pair_t;

/* strncmp-equal over exactly nlen bytes: a shared NUL ends the comparison. */
static int
ref_nameq(const u_char *a, size_t na, const u_char *b, size_t nb)
{
    size_t  i;

    if (na != nb) {
        return 0;
    }
    for (i = 0; i < na; i++) {
        if (a[i] != b[i]) {
            return 0;
        }
        if (a[i] == 0) {
            return 1;
        }
    }
    return 1;
}

static void
check_index(u_char *const *hv, const size_t *hl, size_t nh, int pool_fail)
{
    ngx_http_request_t                   r;
    ngx_pool_t                           pool;
    ngx_http_cache_turbo_cookie_index_t  idx;
    ref_pair_t                          *ref;
    size_t                               total = 1, h, pos, a, e, plen, q, nl;
    size_t                               nref = 0, i, j, eq, v;
    ngx_int_t                            rc = NGX_OK;
    volatile u_char                      sink = 0;

    for (h = 0; h < nh; h++) {
        total += hl[h] + 1;
    }
    ref = malloc(total * sizeof(*ref));
    if (ref == NULL) {
        abort();
    }

    for (h = 0; h < nh; h++) {
        const u_char  *p = hv[h];
        size_t         n = hl[h];

        pos = 0;
        while (pos < n) {
            while (pos < n && (is_ows(p[pos]) || p[pos] == ';')) {
                pos++;
            }
            if (pos >= n) {
                break;
            }
            a = pos;
            while (pos < n && p[pos] != ';') {
                pos++;
            }
            e = pos;
            while (e > a && is_ows(p[e - 1])) {
                e--;
            }
            plen = e - a;
            if (plen == 0) {
                continue;
            }
            eq = NO_VALUE;
            for (q = a; q < e; q++) {
                if (p[q] == '=') {
                    eq = q;
                    break;
                }
            }
            if (eq == NO_VALUE) {
                nl = plen;
                v = a;
            } else {
                nl = eq - a;
                while (nl > 0 && is_ows(p[a + nl - 1])) {
                    nl--;
                }
                v = eq + 1;
                while (v < e && is_ows(p[v])) {
                    v++;
                }
            }
            for (i = 0; i < nref; i++) {
                if (ref_nameq(hv[ref[i].hdr] + ref[i].noff, ref[i].nlen,
                              p + a, nl))
                {
                    break;
                }
            }
            if (i < nref) {
                continue;               /* first occurrence wins */
            }
            ref[nref].hdr = h;
            ref[nref].noff = a;
            ref[nref].nlen = nl;
            ref[nref].voff = v;
            ref[nref].vlen = (eq == NO_VALUE) ? 0 : e - v;
            ref[nref].bare = (eq == NO_VALUE);
            nref++;
        }
    }

    memset(&r, 0, sizeof(r));
    memset(&pool, 0, sizeof(pool));
    pool.fail = pool_fail;
    r.pool = &pool;
    memset(&idx, 0, sizeof(idx));
    idx.pairs = idx.inline_pairs;
    idx.npairs = 0;
    idx.cap = INLINE_PAIRS;

    for (h = 0; h < nh && rc == NGX_OK; h++) {
        rc = ngx_http_cache_turbo_cookie_index_parse_one(&r, &idx, hv[h],
                                                          hl[h]);
    }

    if (pool_fail && nref > INLINE_PAIRS) {
        if (rc != NGX_ERROR) {
            FAIL("cookie_index_parse_one did not fail closed on allocation "
                 "failure");
        }
        goto done;
    }
    if (rc != NGX_OK) {
        FAIL("cookie_index_parse_one failed with an allocation available");
    }
    if (idx.npairs != nref || idx.npairs > idx.cap) {
        FAIL("cookie index pair count differs from the reference");
    }
    if (idx.pairs != idx.inline_pairs
        && (pool.nallocs == 0
            || pool.sizes[pool.nallocs - 1]
               != idx.cap * sizeof(ngx_http_cache_turbo_cookie_pair_t)))
    {
        FAIL("cookie index allocation differs from the computed size");
    }

    for (i = 0; i < nref; i++) {
        const ngx_http_cache_turbo_cookie_pair_t  *pr = &idx.pairs[i];
        const u_char                              *base = hv[ref[i].hdr];

        if (pr->name.data != base + ref[i].noff
            || pr->name.len != ref[i].nlen)
        {
            FAIL("cookie index name differs from the reference");
        }
        if (pr->value.data != base + ref[i].voff
            || pr->value.len != ref[i].vlen)
        {
            FAIL("cookie index value differs from the reference");
        }
        if ((int) pr->bare != ref[i].bare) {
            FAIL("cookie index bare flag differs from the reference");
        }
        /* Touch the bytes: an off-by-one in a bound only shows when read. */
        for (j = 0; j < pr->name.len; j++) {
            sink = (u_char) (sink ^ pr->name.data[j]);
        }
        for (j = 0; j < pr->value.len; j++) {
            sink = (u_char) (sink ^ pr->value.data[j]);
        }
    }
    (void) sink;

done:
    ngx_fuzz_pool_reset(&pool);
    free(ref);
}

/* ---- Cookie Aho-Corasick reference ------------------------------------ */

/* Build the automaton for the masked needles. Returns the exact-sized node
 * array (so a stray state index trips ASan) and its node count. */
static ngx_http_cache_turbo_cookie_ac_node_t *
build_ac(unsigned mask, int empty, ngx_uint_t *nnodes)
{
    ngx_http_cache_turbo_cookie_ac_node_t  *node;
    size_t                                  total = 1, i, c, len;
    size_t                                  n = 1, head = 0, tail = 0;
    size_t                                  st, t, f;
    size_t                                 *queue;

    for (i = 0; i < NNEEDLES; i++) {
        if (mask >> i & 1) {
            total += strlen(kNeedles[i]);
        }
    }
    node = malloc(total * sizeof(*node));
    queue = malloc(total * sizeof(*queue));
    if (node == NULL || queue == NULL) {
        abort();
    }
    for (i = 0; i < total; i++) {
        for (c = 0; c < 256; c++) {
            node[i].next[c] = -1;
        }
        node[i].fail = 0;
        node[i].match = 0;
    }
    node[0].match = empty ? 1 : 0;

    for (i = 0; i < NNEEDLES; i++) {
        if (!(mask >> i & 1)) {
            continue;
        }
        len = strlen(kNeedles[i]);
        st = 0;
        for (c = 0; c < len; c++) {
            u_char  ch = (u_char) kNeedles[i][c];

            if (node[st].next[ch] == -1) {
                node[st].next[ch] = (ngx_int_t) n++;
            }
            st = (size_t) node[st].next[ch];
        }
        node[st].match = 1;
    }

    for (c = 0; c < 256; c++) {
        t = (size_t) node[0].next[c];
        if (node[0].next[c] == -1) {
            node[0].next[c] = 0;
        } else {
            node[t].fail = 0;
            node[t].match |= node[0].match;
            queue[tail++] = t;
        }
    }
    while (head < tail) {
        st = queue[head++];
        for (c = 0; c < 256; c++) {
            f = (size_t) node[st].fail;
            if (node[st].next[c] == -1) {
                node[st].next[c] = node[f].next[c];
            } else {
                t = (size_t) node[st].next[c];
                node[t].fail = node[f].next[c];
                node[t].match |= node[(size_t) node[t].fail].match;
                queue[tail++] = t;
            }
        }
    }

    free(queue);
    *nnodes = (ngx_uint_t) n;
    return node;
}

static int
ref_ac(const u_char *p, size_t n, unsigned mask, int empty)
{
    size_t  tn, i, nl, off;

    if (empty && n > 0) {
        return 1;
    }
    for (tn = 0; tn < n && p[tn] != 0; tn++) {
        /* tn ends at the first NUL */
    }
    for (i = 0; i < NNEEDLES; i++) {
        if (!(mask >> i & 1)) {
            continue;
        }
        nl = strlen(kNeedles[i]);
        for (off = 0; off + nl <= tn; off++) {
            if (memcmp(p + off, kNeedles[i], nl) == 0) {
                return 1;
            }
        }
    }
    return 0;
}

static void
check_ac(u_char *const *hv, const size_t *hl, size_t nh, unsigned mask,
    int empty, int no_nodes, int null_data)
{
    ngx_http_cache_turbo_cookie_ac_t  ac;
    size_t                            h;
    ngx_uint_t                        nnodes = 0;
    ngx_int_t                         got, want;

    memset(&ac, 0, sizeof(ac));
    if (!no_nodes) {
        ac.nodes = build_ac(mask, empty, &nnodes);
        ac.nnodes = nnodes;
        ac.cap = nnodes;
    }

    for (h = 0; h < nh; h++) {
        got = ngx_http_cache_turbo_cookie_ac_scan_one(
                  &ac, null_data ? NULL : hv[h], hl[h]);
        want = (no_nodes || null_data || hl[h] == 0)
               ? 0 : ref_ac(hv[h], hl[h], mask, empty);
        if (got != want) {
            FAIL("cookie_ac_scan_one differs from the reference");
        }
    }
    if (ngx_http_cache_turbo_cookie_ac_scan_one(&ac, NULL, 0) != 0) {
        FAIL("cookie_ac_scan_one matched NULL data");
    }

    free(ac.nodes);
}

int
LLVMFuzzerTestOneInput(const uint8_t *data, size_t size)
{
    const uint8_t  *sec[MAX_HDRS + 1];
    size_t          slen[MAX_HDRS + 1];
    u_char         *hv[MAX_HDRS];
    size_t          hl[MAX_HDRS];
    size_t          nsec = 0, nh, pos, end, i;
    unsigned        flags, mask, sel;

    if (size < 3) {
        return 0;
    }
    flags = data[0];
    mask = data[1] & ((1u << NNEEDLES) - 1);
    sel = data[2];
    data += 3;
    size -= 3;

    pos = 0;
    while (nsec < MAX_HDRS + 1) {
        end = pos;
        if (nsec == MAX_HDRS) {
            end = size;                 /* the rest belongs to the last one */
        } else {
            while (end < size && data[end] != 0xFF) {
                end++;
            }
        }
        sec[nsec] = data + pos;
        slen[nsec] = end - pos;
        nsec++;
        if (end >= size) {
            break;
        }
        pos = end + 1;
    }

    check_args(sec[0], slen[0], flags & 1, sel);

    nh = nsec - 1;
    for (i = 0; i < nh; i++) {
        hl[i] = slen[i + 1];
        hv[i] = dup_exact(sec[i + 1], hl[i]);
    }

    check_index(hv, hl, nh, flags & 1);
    check_ac(hv, hl, nh, mask, (flags >> 1) & 1, (flags >> 2) & 1,
             (flags >> 3) & 1);

    for (i = 0; i < nh; i++) {
        free(hv[i]);
    }
    return 0;
}
