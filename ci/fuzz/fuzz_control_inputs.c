/*
 * libFuzzer harness for the cache-turbo control-input parsers:
 *   ngx_http_cache_turbo_hexdecode()                (purge.c, + match.c hexval)
 *   ngx_http_cache_turbo_body_filter_tag_split()    (filters.c)
 *   ngx_http_cache_turbo_warm() and _warm_file_finish()
 *                                       (admin.c, + warm_uri_is_safe/_raw_is_safe)
 *
 * Why this target: these are the operator/origin-controlled byte walkers the
 * other targets never reach. hexdecode turns a tag-set member read back from L2
 * into a key digest (odd length, non-hex escapes); tag_split tokenises an
 * UPSTREAM-controlled Surrogate-Key / Cache-Tag value into at most
 * NGX_HTTP_CACHE_TURBO_MAX_TAGS entries of at most MAX_TAG_LEN bytes (empty
 * tags, separator runs, thousands of tags, over-long tags); warm() splits an
 * admin-supplied URL list (query string or ?url_file= contents) on ',' and
 * '\n', trims a CR, splits the "?query" suffix, percent-decodes the path into an
 * exact-sized allocation and gates the decoded path and the RAW span (which is
 * spliced onto the wire) before firing a bounded number of subrequests;
 * warm_file_finish rejects a list holding a line over WARM_LINE_MAX_LEN. Bug
 * classes: an OOB read at/over the end of an exact-sized, NON-NUL-terminated
 * buffer (every input is its own heap block so ASan sees it), a write past the
 * seen[] array or the decode allocation, a cap that stops holding, and a
 * CR/NUL/CTL byte reaching the subrequest.
 *
 * Function ownership: these functions are compiled into no other fuzz target
 * (hexval is also sliced into fuzz_cookie_args / fuzz_auto_classify, where it is
 * the argparse helper; here it is asserted through hexdecode). The query
 * argument LOOKUP (ngx_http_arg for ?url= / ?url_file= / ?tag= / ?key=) is
 * nginx core and is not driven; the "?query" suffix reader of warm() is. See
 * ci/fuzz/README.md.
 *
 * Input layout:
 *   byte 0   bits 0-2  warm_max selector (kWarmMax[])
 *            bits 3-4  warm_one failure schedule (0 none, 1 all, 2 evens,
 *                      3 all but every third)
 *            bit 5     pool failure enabled
 *            bit 6     resume tag_split from the returned cursor
 *   byte 1   pool failure index (the Nth ngx_pnalloc and every later one fail)
 *   bytes 2..  sections: 0 = hex string, 1 = tag value (both end at the first
 *            0xFF), 2 = warm list (the rest of the input). Each is an
 *            exact-sized heap buffer, no trailing NUL.
 *
 * Oracle (independent index-based reference models):
 *   hexdecode: NGX_OK iff the length is even and every byte is hex; the output
 *     equals the reference; an odd length writes nothing.
 *   tag_split: CAP ORACLE - count never exceeds MAX_TAGS and every tag is
 *     1..MAX_TAG_LEN bytes inside the value with no separator, distinct; the
 *     tags, the cursor and the over-long-tag warning count equal the
 *     reference (cursor == end of value unless the count cap stopped it).
 *   warm: every subrequest call (decoded path, "?query" args, raw span)
 *     equals the reference; the number of successful subrequests never exceeds
 *     warm_max; the reply reports exactly that count; a failing pool returns
 *     500 with no reply; every decoded path is absolute, NUL-free and has no
 *     ".." segment, every raw span has no byte <= 0x20 or 0x7f.
 *   warm_file_finish: a list with any '\n'-delimited line over
 *     WARM_LINE_MAX_LEN gets the 500 error reply and fires nothing; otherwise
 *     it equals warm().
 *
 * Bodies are sliced by extract_control_inputs.sh into
 * generated_control_inputs.inc. Build: ci/fuzz/build.sh.
 */

#include <stdio.h>

#include "ngx_shim_control_inputs.h"

/* Generated by ci/fuzz/extract_control_inputs.sh. */
#include "generated_control_inputs.inc"

#define FAIL(msg)                                                            \
    do {                                                                     \
        fprintf(stderr, "fuzz_control_inputs: %s\n", msg);                   \
        __builtin_trap();                                                    \
    } while (0)

static const size_t kWarmMax[8] = { 0, 1, 2, 3, 32, 64, 1000, 4096 };

static u_char *
dup_exact(const uint8_t *p, size_t n)
{
    u_char  *d = malloc(n ? n : 1);

    if (d == NULL) {
        abort();
    }
    if (n) {
        memcpy(d, p, n);
    }
    return d;
}

/* ---- hexdecode --------------------------------------------------------- */

static int
ref_nib(unsigned c)
{
    static const char  digits[] = "0123456789abcdef";
    const char        *at;

    if (c >= 'A' && c <= 'F') {
        c += 'a' - 'A';
    }
    if (c == 0) {
        return -1;
    }
    at = strchr(digits, (int) c);
    return at == NULL ? -1 : (int) (at - digits);
}

static void
check_hex(const uint8_t *in, size_t n)
{
    u_char     *src = dup_exact(in, n);
    u_char     *dst = malloc(n / 2 ? n / 2 : 1);
    size_t      i;
    int         ok = (n % 2 == 0);
    ngx_int_t   rc;

    if (dst == NULL) {
        abort();
    }
    memset(dst, 0xA5, n / 2 ? n / 2 : 1);

    for (i = 0; i < n; i++) {
        if (ref_nib(src[i]) < 0) {
            ok = 0;
        }
    }

    rc = ngx_http_cache_turbo_hexdecode(src, n, dst);

    if (ok) {
        if (rc != NGX_OK) {
            FAIL("hexdecode rejected a valid hex string");
        }
        for (i = 0; i < n; i += 2) {
            if (dst[i / 2] != (u_char) ((ref_nib(src[i]) << 4)
                                        | ref_nib(src[i + 1])))
            {
                FAIL("hexdecode output differs from the reference");
            }
        }
    } else {
        if (rc != NGX_ERROR) {
            FAIL("hexdecode accepted an odd length or a non-hex byte");
        }
        if (n % 2 == 1) {
            for (i = 0; i < n / 2; i++) {
                if (dst[i] != 0xA5) {
                    FAIL("hexdecode wrote output for an odd length");
                }
            }
        }
    }

    free(src);
    free(dst);
}

/* ---- tag_split ---------------------------------------------------------- */

typedef struct {
    size_t  off;
    size_t  len;
} ref_tag_t;

static int
ref_tag_sep(int c)
{
    return c == ' ' || c == '\t' || c == ',' || c == '\r' || c == '\n';
}

/* Whole-value tokenisation first, caps applied after. */
static size_t
ref_tags(const u_char *v, size_t n, size_t from, ref_tag_t *out,
    size_t *cursor, unsigned long *warns)
{
    size_t  pos = from, start, end, cnt = 0, k;

    *warns = 0;
    for (;;) {
        while (pos < n && ref_tag_sep(v[pos])) {
            pos++;
        }
        if (pos >= n) {
            *cursor = n;
            return cnt;
        }
        start = pos;
        while (pos < n && !ref_tag_sep(v[pos])) {
            pos++;
        }
        end = pos;
        if (end - start > NGX_HTTP_CACHE_TURBO_MAX_TAG_LEN) {
            (*warns)++;
            continue;
        }
        for (k = 0; k < cnt; k++) {
            if (out[k].len == end - start
                && memcmp(v + out[k].off, v + start, end - start) == 0)
            {
                break;
            }
        }
        if (k < cnt) {
            continue;
        }
        out[cnt].off = start;
        out[cnt].len = end - start;
        cnt++;
        if (cnt == NGX_HTTP_CACHE_TURBO_MAX_TAGS) {
            *cursor = end;
            return cnt;
        }
    }
}

static void
check_tags_from(u_char *v, size_t n, u_char *from)
{
    ngx_http_request_t  r;
    ngx_connection_t    conn;
    ngx_str_t          *seen;
    ngx_pool_t          pool;
    ref_tag_t           want[NGX_HTTP_CACHE_TURBO_MAX_TAGS];
    unsigned long       want_warns;
    size_t              want_cursor, want_n, i, j;
    ngx_uint_t          got_n;
    u_char             *s = from;

    memset(&pool, 0, sizeof(pool));
    conn.log = NULL;
    r.uri.len = 0;
    r.uri.data = NULL;
    r.args = r.uri;
    r.pool = &pool;
    r.connection = &conn;

    /* Exactly MAX_TAGS entries: a write of the 17th is an ASan report. */
    seen = malloc(NGX_HTTP_CACHE_TURBO_MAX_TAGS * sizeof(ngx_str_t));
    if (seen == NULL) {
        abort();
    }

    ngx_fuzz_warns = 0;
    got_n = ngx_http_cache_turbo_body_filter_tag_split(&r, &s, v + n, seen);

    /* CAP ORACLE: the documented bounds, asserted before any comparison. */
    if (got_n > NGX_HTTP_CACHE_TURBO_MAX_TAGS) {
        FAIL("tag count exceeds NGX_HTTP_CACHE_TURBO_MAX_TAGS");
    }
    for (i = 0; i < got_n; i++) {
        if (seen[i].len == 0 || seen[i].len > NGX_HTTP_CACHE_TURBO_MAX_TAG_LEN)
        {
            FAIL("tag length outside 1..NGX_HTTP_CACHE_TURBO_MAX_TAG_LEN");
        }
        if (seen[i].data < v || seen[i].data + seen[i].len > v + n) {
            FAIL("tag points outside the value");
        }
        for (j = 0; j < seen[i].len; j++) {
            if (ref_tag_sep(seen[i].data[j])) {
                FAIL("tag contains a separator");
            }
        }
        for (j = 0; j < i; j++) {
            if (seen[j].len == seen[i].len
                && memcmp(seen[j].data, seen[i].data, seen[i].len) == 0)
            {
                FAIL("duplicate tag returned");
            }
        }
    }
    if (s < from || s > v + n) {
        FAIL("cursor left the value");
    }

    want_n = ref_tags(v, n, (size_t) (from - v), want, &want_cursor,
                      &want_warns);
    if (got_n != want_n) {
        FAIL("tag count differs from the reference");
    }
    for (i = 0; i < want_n; i++) {
        if (seen[i].data != v + want[i].off || seen[i].len != want[i].len) {
            FAIL("tag differs from the reference");
        }
    }
    if ((size_t) (s - v) != want_cursor) {
        FAIL("cursor differs from the reference");
    }
    if (got_n < NGX_HTTP_CACHE_TURBO_MAX_TAGS && s != v + n) {
        FAIL("cursor stopped short without reaching the tag cap");
    }
    if (ngx_fuzz_warns != want_warns) {
        FAIL("over-long tag warning count differs from the reference");
    }

    free(seen);
    free(pool.allocs);
}

static void
check_tags(u_char *v, size_t n, int resume)
{
    ngx_http_request_t  r;
    ngx_connection_t    conn;
    ngx_pool_t          pool;
    ngx_str_t           seen[NGX_HTTP_CACHE_TURBO_MAX_TAGS];
    u_char             *s = v;

    check_tags_from(v, n, v);
    if (!resume) {
        return;
    }

    /* The caller resumes from the returned cursor to detect the count cap. */
    memset(&pool, 0, sizeof(pool));
    conn.log = NULL;
    r.uri.len = 0;
    r.uri.data = NULL;
    r.args = r.uri;
    r.pool = &pool;
    r.connection = &conn;
    (void) ngx_http_cache_turbo_body_filter_tag_split(&r, &s, v + n, seen);
    check_tags_from(v, n, s);
}

/* ---- warm / warm_file_finish ------------------------------------------- */

typedef struct {
    u_char  *dec;           /* malloc'd decoded path */
    size_t   dec_len;
    size_t   args_off, args_len;
    size_t   raw_off, raw_len;
} ref_call_t;

typedef struct {
    ref_call_t  *calls;
    size_t       ncalls, cap;
    size_t       succ;
    int          alloc_failed;
} ref_warm_t;

static int
ref_decode(const u_char *p, size_t n, u_char *out)
{
    size_t  i = 0, o = 0;
    int     h1, h2;

    while (i < n) {
        if (p[i] != '%') {
            out[o++] = p[i++];
            continue;
        }
        i++;                               /* the '%' */
        if (i >= n) {
            break;
        }
        h1 = ref_nib(p[i]);
        if (h1 < 0) {
            out[o++] = p[i++];             /* invalid first digit: kept */
            continue;
        }
        i++;
        if (i >= n) {
            break;
        }
        h2 = ref_nib(p[i]);
        i++;
        if (h2 >= 0) {
            out[o++] = (u_char) ((h1 << 4) | h2);
        }                                  /* invalid second digit: dropped */
    }
    return (int) o;
}

static int
ref_path_safe(const u_char *d, size_t n)
{
    size_t  i, j;

    for (i = 0; i < n; i++) {
        if (d[i] == 0) {
            return 0;
        }
    }
    i = 1;
    while (i <= n) {
        j = i;
        while (j < n && d[j] != '/') {
            j++;
        }
        if (j - i == 2 && d[i] == '.' && d[i + 1] == '.') {
            return 0;
        }
        i = j + 1;
    }
    return 1;
}

static int
ref_raw_safe(const u_char *p, size_t n)
{
    size_t  i;

    for (i = 0; i < n; i++) {
        if (p[i] <= 0x20 || p[i] == 0x7f) {
            return 0;
        }
    }
    return 1;
}

static void
ref_warm(const u_char *v, size_t n, size_t warm_max, unsigned pattern,
    size_t fail_at, ref_warm_t *out)
{
    size_t  pos = 0, e, ulen, rend, qpos, plen, nreq = 0, calls = 0, k;
    u_char *dec;
    int     dl;

    memset(out, 0, sizeof(*out));
    while (pos < n && out->succ < warm_max) {
        e = pos;
        while (e < n && v[e] != ',' && v[e] != '\n') {
            e++;
        }
        if (e > pos) {
            ulen = e - pos;
            rend = e;
            if (v[e - 1] == '\r') {
                ulen--;
                rend--;
            }
            qpos = ulen;
            for (k = 0; k < ulen; k++) {
                if (v[pos + k] == '?') {
                    qpos = k;
                    break;
                }
            }
            plen = qpos;
            if (plen > 0 && v[pos] == '/') {
                if (nreq++ >= fail_at) {
                    out->alloc_failed = 1;
                    return;
                }
                dec = malloc(plen);
                if (dec == NULL) {
                    abort();
                }
                dl = ref_decode(v + pos, plen, dec);
                if (dl > 0 && dec[0] == '/' && ref_path_safe(dec, (size_t) dl)
                    && ref_raw_safe(v + pos, rend - pos))
                {
                    if (out->ncalls == out->cap) {
                        out->cap = out->cap ? out->cap * 2 : 256;
                        out->calls = realloc(out->calls,
                                             out->cap * sizeof(ref_call_t));
                        if (out->calls == NULL) {
                            abort();
                        }
                    }
                    out->calls[out->ncalls].dec = dec;
                    out->calls[out->ncalls].dec_len = (size_t) dl;
                    out->calls[out->ncalls].args_off =
                        qpos < ulen ? pos + qpos + 1 : 0;
                    out->calls[out->ncalls].args_len =
                        qpos < ulen ? ulen - qpos - 1 : 0;
                    out->calls[out->ncalls].raw_off = pos;
                    out->calls[out->ncalls].raw_len = rend - pos;
                    out->ncalls++;
                    if (!ngx_fuzz_warm_fails(calls++, pattern)) {
                        out->succ++;
                    }
                } else {
                    free(dec);
                }
            }
        }
        if (e >= n) {
            break;
        }
        pos = e + 1;
    }
    if (nreq++ >= fail_at) {            /* the reply buffer */
        out->alloc_failed = 1;
    }
}

static void
ref_warm_free(ref_warm_t *w)
{
    size_t  i;

    for (i = 0; i < w->ncalls; i++) {
        free(w->calls[i].dec);
    }
    free(w->calls);
}

static void
warm_reset(void)
{
    ngx_fuzz_ncalls = 0;
    ngx_fuzz_replies = 0;
    ngx_fuzz_reply_status = 0;
    ngx_fuzz_reply_body[0] = '\0';
}

static void
check_warm_result(const u_char *v, size_t n, size_t warm_max, ngx_int_t rc,
    const ref_warm_t *w)
{
    size_t  i;
    char    want[64];

    if (w->alloc_failed) {
        if (rc != NGX_HTTP_INTERNAL_SERVER_ERROR || ngx_fuzz_replies != 0) {
            FAIL("a failing pool must return 500 with no reply");
        }
    } else {
        snprintf(want, sizeof(want), "{\"warmed\":%lu}\n",
                 (unsigned long) w->succ);
        if (w->succ > warm_max) {
            FAIL("reference exceeded warm_max (model bug)");
        }
        if (ngx_fuzz_replies != 1 || ngx_fuzz_reply_status != NGX_HTTP_OK
            || rc != NGX_HTTP_OK
            || strcmp(ngx_fuzz_reply_body, want) != 0)
        {
            FAIL("warm reply differs from the reference count");
        }
    }

    if (ngx_fuzz_ncalls != w->ncalls) {
        FAIL("number of warm subrequests differs from the reference");
    }
    for (i = 0; i < ngx_fuzz_ncalls; i++) {
        const ngx_fuzz_warm_call_t  *c = &ngx_fuzz_calls[i];
        const ref_call_t            *x = &w->calls[i];
        size_t                       k;

        if (c->uri_len != x->dec_len
            || memcmp(c->uri, x->dec, x->dec_len) != 0)
        {
            FAIL("decoded warm path differs from the reference");
        }
        if (c->uri_len == 0 || c->uri[0] != '/') {
            FAIL("warm path is not absolute");
        }
        for (k = 0; k < c->uri_len; k++) {
            if (c->uri[k] == 0) {
                FAIL("NUL byte in a warm path");
            }
        }
        if (c->args_len != x->args_len
            || (x->args_len && c->args != v + x->args_off))
        {
            FAIL("warm query args differ from the reference");
        }
        if (c->raw != v + x->raw_off || c->raw_len != x->raw_len) {
            FAIL("warm raw span differs from the reference");
        }
        for (k = 0; k < c->raw_len; k++) {
            if (c->raw[k] <= 0x20 || c->raw[k] == 0x7f) {
                FAIL("control byte in a warm raw span");
            }
        }
    }
    (void) n;
}

static void
check_warm(const uint8_t *in, size_t n, size_t warm_max, unsigned pattern,
    size_t fail_at)
{
    ngx_http_request_t  r;
    ngx_connection_t    conn;
    ngx_pool_t          pool;
    ref_warm_t          w;
    u_char             *list = dup_exact(in, n);
    size_t              pos, line_start;
    int                 too_long = 0;
    ngx_str_t           urls;
    ngx_int_t           rc;

    memset(&pool, 0, sizeof(pool));
    pool.fail_at = fail_at;
    conn.log = NULL;
    r.uri.len = 0;
    r.uri.data = NULL;
    r.args = r.uri;
    r.pool = &pool;
    r.connection = &conn;
    urls.data = list;
    urls.len = n;
    ngx_fuzz_warm_pattern = pattern;

    ref_warm(list, n, warm_max, pattern, fail_at, &w);

    /* warm() itself */
    warm_reset();
    rc = ngx_http_cache_turbo_warm(&r, &urls, (ngx_int_t) warm_max);
    check_warm_result(list, n, warm_max, rc, &w);
    ngx_fuzz_pool_reset(&pool);

    /* warm_file_finish(): the per-line length gate in front of warm() */
    line_start = 0;
    for (pos = 0; pos <= n; pos++) {
        if (pos == n || list[pos] == '\n') {
            if (pos - line_start > NGX_HTTP_CACHE_TURBO_WARM_LINE_MAX_LEN) {
                too_long = 1;
            }
            line_start = pos + 1;
        }
    }

    warm_reset();
    rc = ngx_http_cache_turbo_warm_file_finish(&r, &urls,
                                               (ngx_int_t) warm_max);
    if (too_long) {
        if (rc != NGX_HTTP_INTERNAL_SERVER_ERROR || ngx_fuzz_replies != 1
            || ngx_fuzz_reply_status != NGX_HTTP_INTERNAL_SERVER_ERROR
            || strncmp(ngx_fuzz_reply_body, "{\"error\"", 8) != 0
            || ngx_fuzz_ncalls != 0)
        {
            FAIL("warm_file_finish accepted an over-long line");
        }
    } else {
        check_warm_result(list, n, warm_max, rc, &w);
    }
    ngx_fuzz_pool_reset(&pool);

    ref_warm_free(&w);
    free(pool.allocs);
    free(list);
}

int
LLVMFuzzerTestOneInput(const uint8_t *data, size_t size)
{
    const uint8_t  *sec[3];
    size_t          slen[3], pos, end, i;
    unsigned        flags;
    size_t          fail_at;
    u_char         *tags;

    if (size < 2) {
        return 0;
    }
    flags = data[0];
    fail_at = (flags >> 5 & 1) ? data[1] : (size_t) -1;
    data += 2;
    size -= 2;

    pos = 0;
    for (i = 0; i < 3; i++) {
        end = pos;
        if (i < 2) {
            while (end < size && data[end] != 0xFF) {
                end++;
            }
        } else {
            end = size;                 /* the rest is the warm list */
        }
        sec[i] = data + pos;
        slen[i] = end - pos;
        pos = end < size ? end + 1 : size;
    }

    check_hex(sec[0], slen[0]);

    tags = dup_exact(sec[1], slen[1]);
    check_tags(tags, slen[1], (flags >> 6) & 1);
    free(tags);

    check_warm(sec[2], slen[2], kWarmMax[flags & 7], (flags >> 3) & 3,
               fail_at);
    return 0;
}
